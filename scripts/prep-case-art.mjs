/**
 * Turns the clinical case photographs into the Cases section's artwork.
 *
 * The masters are WhatsApp exports (1280 on the long edge, JPEG) and arrive in
 * two orientations plus one stacked before/after composite. Every master is
 * written at two widths so the grid can pick a size for the box it paints in,
 * and the composite is split at its seam into a real before/after pair for the
 * comparison slider.
 *
 * Alongside the WebP files a manifest records each derivative's pixel size and
 * a ~24px blurred preview as a data URI, so a card can paint something the
 * moment it mounts and swap in the photograph when it has loaded.
 *
 *   node scripts/prep-case-art.mjs
 */
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises'
import sharp from 'sharp'

const SRC = 'brand/cases'
const OUT = 'src/assets/cases'
const SMALL = 640
const WEBP = { quality: 82, effort: 6 }

/**
 * One entry per shipped image. `split` cuts the composite: `top` and `bottom`
 * are the two halves' output names, `seam` the row (as a fraction of the
 * master's height) the two photographs meet on — measured, not assumed.
 */
const SOURCES = [
  { name: 'full-arch-both' },
  { name: 'upper-arch-fixed' },
  { name: 'smile-portrait' },
  { name: 'upper-arch-closeup' },
  { name: 'full-mouth-smile' },
  { name: 'anterior-crowns-retractor' },
  { name: 'anterior-crowns-smile' },
  { name: 'lab-master-cast' },
  { name: 'veneers-composite', split: { top: 'veneers-after', bottom: 'veneers-before', seam: 0.5 } },
]

await mkdir(OUT, { recursive: true })

const manifest = {}

async function emit(name, input) {
  const meta = await sharp(input).metadata()
  const entry = { width: meta.width, height: meta.height }

  const large = await sharp(input).webp(WEBP).toBuffer()
  await writeFile(`${OUT}/${name}-lg.webp`, large)
  entry.lg = { width: meta.width, height: meta.height }

  const smallInfo = await sharp(input)
    .resize({ width: SMALL, withoutEnlargement: true })
    .webp(WEBP)
    .toFile(`${OUT}/${name}-sm.webp`)
  entry.sm = { width: smallInfo.width, height: smallInfo.height }

  // The placeholder: tiny, soft, and encoded inline. ~300 bytes each.
  const blur = await sharp(input)
    .resize({ width: 24 })
    .blur(1.2)
    .webp({ quality: 40 })
    .toBuffer()
  entry.blur = `data:image/webp;base64,${blur.toString('base64')}`

  manifest[name] = entry
  const { size } = await stat(`${OUT}/${name}-lg.webp`)
  console.log(`${name}  ${meta.width}x${meta.height}  lg ${(size / 1024).toFixed(0)} kB  sm ${(smallInfo.size / 1024).toFixed(0)} kB`)
}

for (const source of SOURCES) {
  const input = await readFile(`${SRC}/${source.name}.jpeg`)

  if (!source.split) {
    await emit(source.name, input)
    continue
  }

  const meta = await sharp(input).metadata()
  const seam = Math.round(meta.height * source.split.seam)
  const top = await sharp(input).extract({ left: 0, top: 0, width: meta.width, height: seam }).toBuffer()
  const bottom = await sharp(input)
    .extract({ left: 0, top: seam, width: meta.width, height: meta.height - seam })
    .toBuffer()
  await emit(source.split.top, top)
  await emit(source.split.bottom, bottom)
}

// A TypeScript module rather than JSON: the sizes and previews are then typed
// `as const`, and the bundler config needs no JSON-resolution flag for them.
const header =
  '// Generated by scripts/prep-case-art.mjs — do not edit by hand.\n' +
  '// Pixel sizes and inline blurred previews for every shipped case photograph.\n\n'
await writeFile(
  `${OUT}/manifest.ts`,
  `${header}export const CASE_ART = ${JSON.stringify(manifest, null, 2)} as const\n`,
)
console.log(`manifest: ${Object.keys(manifest).length} images`)
